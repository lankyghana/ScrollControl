import java.util.Properties
import java.io.FileInputStream

plugins {
    id("com.android.application")
    id("kotlin-android")
    // The Flutter Gradle Plugin must be applied after the Android and Kotlin Gradle plugins.
    id("dev.flutter.flutter-gradle-plugin")
}

// Release signing — populated from android/key.properties (gitignored, not
// committed). If that file is missing (e.g. a fresh checkout that hasn't
// generated a keystore yet), release builds fall back to debug signing so
// `flutter run --release` still works, but that build must never be
// uploaded to Play.
val keystoreProperties = Properties()
val keystorePropertiesFile = rootProject.file("key.properties")
val hasReleaseSigning = keystorePropertiesFile.exists()
if (hasReleaseSigning) {
    keystoreProperties.load(FileInputStream(keystorePropertiesFile))
} else {
    logger.warn(
        "WARNING: android/key.properties not found — release build will be " +
            "signed with the DEBUG key. Do not upload this build to Play. " +
            "See README for how to generate a release keystore."
    )
}

